function makeBaseNode(
  partial: Partial<CanvasNode> &
    Pick<CanvasNode, 'id' | 'name' | 'type' | 'x' | 'y' | 'width' | 'height'>,
): CanvasNode {
  return {
    rotation: 0,
    radius: 12,
    opacity: 1,
    fill: { kind: 'solid', color: '#151924' },
    strokeColor: '#2A3147',
    strokeWidth: 0,
    blur: 0,
    shadow: 'none',
    blendMode: 'normal',
    locked: false,
    visible: true,
    ...partial,
  };
}

